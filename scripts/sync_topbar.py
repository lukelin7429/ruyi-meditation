ACTIVE_RE = re.compile(r'<a href="([^"]+)"[^>]*class="active"')
STICKY_RE = re.compile(r'\.site-header\s*{[^}]*position\s*:\s*sticky', re.S)


def detect(text):
    """Preserve what the page already declares: which nav item is active, and
    whether its bar is sticky. Reading pages are static (their .tabs bar is
    sticky); section pages like english-school are sticky and stay that way."""
    m = ACTIVE_RE.search(text)
    active = m.group(1) if m else '/dharma/'
    return active, ('sticky' if STICKY_RE.search(text) else 'static')


def build(active, position):
    css = CANONICAL_CSS.replace('__BASE__', BASE_STICKY if position == 'sticky' else BASE_STATIC)
    header = HEADER_TPL.replace('__NAV6__', nav_links(active, '      '))
    drawer = DRAWER_TPL.replace('__NAV6__', nav_links(active, '      '))
    return css, header, drawer


CSS_RE    = re.compile(r'<style id="ruyi-topbar">.*?</style>\n?', re.S)
HEADER_RE = re.compile(r'<header class="site-header">.*?</header>', re.S)
DRAWER_RE = re.compile(r'\n?<div class="mobile-nav-drawer".*?</div>\s*<script id="ruyi-topbar-js">.*?</script>', re.S)


def targets():
    out = []
    for dp, dn, fn in os.walk(REPO):
        dn[:] = [d for d in dn if d not in SKIP_DIRS and not d.startswith('.')]
        for f in sorted(fn):
            if not f.endswith('.html'):
                continue
            p = os.path.join(dp, f)
            t = io.open(p, encoding='utf-8', errors='replace').read()
            if t.lstrip().startswith('---'):
                continue                      # Jekyll page: uses the include
            if '<header class="site-header">' not in t:
                continue                      # not a bar-carrying standalone page
            out.append(p)
    return sorted(out)


def dedupe(text):
    """A handful of Sutta Nipata pages were injected twice at some point and
    carry two <body> tags and two identical headers. Keep the first of each."""
    hdrs = list(HEADER_RE.finditer(text))
    if len(hdrs) <= 1:
        return text
    out = text
    for m in reversed(hdrs[1:]):
        start, end = m.start(), m.end()
        stray = re.search(r'<body[^>]*>\s*$', out[:start])   # the stray <body> too
        if stray:
            start = stray.start()
        out = out[:start] + out[end:]
    return out


def sync(text):
    """Return the page with a canonical bar, or None if nothing would change."""
    if not HEADER_RE.search(text):
        return None
    active, position = detect(text)
    css, header, drawer = build(active, position)
    new = dedupe(text)
    new = DRAWER_RE.sub('', new)                        # drop any previous drawer
    if CSS_RE.search(new):
        new = CSS_RE.sub(lambda m: css, new, count=1)
    elif '</head>' in new:
        # A few section pages (english-school) hand-rolled their bar without the
        # marker block. Their old rules stay where they are but are unscoped and
        # earlier in the document, so this scoped block placed last wins.
        new = new.replace('</head>', css + '</head>', 1)
    else:
        return None
    new = HEADER_RE.sub(lambda m: header + '\n' + drawer, new, count=1)
    return None if new == text else new


if __name__ == '__main__':
    apply = '--apply' in sys.argv
    limit = None
    if '--limit' in sys.argv:
        limit = int(sys.argv[sys.argv.index('--limit') + 1])
    files = targets()
    if limit:
        files = files[:limit]
    changed = skipped = 0
    for p in files:
        t = io.open(p, encoding='utf-8', errors='replace').read()
        new = sync(t)
        if new is None:
            skipped += 1
            continue
        changed += 1
        if apply:
            io.open(p, 'w', encoding='utf-8').write(new)
    verb = 'updated' if apply else 'would update'
    print(f'{len(files)} bar-carrying standalone pages found')
    print(f'  {verb}: {changed}')
    print(f'  already canonical: {skipped}')
    if not apply:
        print('\n(dry run — pass --apply to write)')
