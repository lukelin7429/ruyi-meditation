#!/usr/bin/env python3
"""
Keep the Ru-Yi top bar on the standalone (non-Jekyll) pages in sync with the
shared one.

The reading pages under discourses/ (and a few others) are authored as complete
standalone HTML documents with their own self-contained design, so they cannot
use _includes/header.html. Instead they carry an inlined copy of the bar. This
script is the single place that copy is defined: edit CANONICAL_CSS / HEADER /
DRAWER here and re-run, never hand-edit the pages.

Unlike the older scripts/add_topbar.py (which only ever added a bar to pages
that had none), this REPLACES whatever bar is already there, so the copy can be
corrected after the fact. It is idempotent: running it twice changes nothing.

  python3 scripts/sync_topbar.py            # dry run, reports what would change
  python3 scripts/sync_topbar.py --apply    # write the changes
  python3 scripts/sync_topbar.py --limit 3 --apply   # first 3 files only

position:static is deliberate. These pages have their own sticky elements (the
.tabs bar on a discourse page); a sticky header would stack on top of them.
Log In / Sign Up are deliberately absent too — they are not on these pages
today, they would widen the bar by ~164px, and the cross-domain session script
that drives them is not loaded here.
"""
